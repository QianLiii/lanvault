    def generate_keypair(self) -> tuple[str, str]:
        """Return (private_pem, public_pem) generated by openssl."""
        with tempfile.TemporaryDirectory() as tmp:
            key_path = Path(tmp) / "key.pem"
            pub_path = Path(tmp) / "pub.pem"
            subprocess.run(
                [
                    "openssl",
                    "genpkey",
                    "-algorithm",
                    "EC",
                    "-pkeyopt",
                    "ec_paramgen_curve:P-256",
                    "-out",
                    str(key_path),
                ],
                check=True,
                capture_output=True,
            )
            subprocess.run(
                [
                    "openssl",
                    "pkey",
                    "-in",
                    str(key_path),
                    "-pubout",
                    "-out",
                    str(pub_path),
                ],
                check=True,
                capture_output=True,
            )
            return (
                key_path.read_text(encoding="utf-8"),
                pub_path.read_text(encoding="utf-8"),
            )

    @staticmethod
    def der_to_raw_p256(der: bytes) -> bytes:
        """Convert an openssl DER ECDSA signature to the raw r||s form browsers send."""
        if len(der) < 8 or der[0] != 0x30:
            raise ValueError("not a DER signature")
        index = 2 if der[1] < 0x80 else 3

        def read_int() -> bytes:
            nonlocal index
            if der[index] != 0x02:
                raise ValueError("expected DER INTEGER")
            index += 1
            length = der[index]
            index += 1
            value = der[index : index + length]
            index += length
            value = value.lstrip(b"\x00") or b"\x00"
            if len(value) > 32:
                raise ValueError("integer too large for P-256")
            return value.rjust(32, b"\x00")

        raw = read_int() + read_int()
        if len(raw) != 64:
            raise ValueError("not a P-256 signature")
        return raw

    def sign_message(self, private_pem: str, message: bytes) -> bytes:
        """Return an openssl DER signature over message."""
        with tempfile.TemporaryDirectory() as tmp:
            key_path = Path(tmp) / "key.pem"
            message_path = Path(tmp) / "message.bin"
            signature_path = Path(tmp) / "signature.der"
            key_path.write_text(private_pem, encoding="utf-8")
            message_path.write_bytes(message)
            subprocess.run(
                [
                    "openssl",
                    "dgst",
                    "-sha256",
                    "-sign",
                    str(key_path),
                    "-out",
                    str(signature_path),
                    str(message_path),
                ],
                check=True,
                capture_output=True,
            )
            return signature_path.read_bytes()

