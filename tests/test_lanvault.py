    def test_quick_access_is_per_user_and_persisted(self) -> None:
        cookie = self.login()

        status, _, body = self.request("GET", "/api/quick-access", cookie=cookie)
        self.assertEqual(status, 200)
        self.assertEqual(self.json_body(body)["entries"], [])

        status, _, _ = self.request(
            "POST",
            "/api/quick-access",
            json.dumps({"path": "docs/notes.txt"}),
            headers={"Content-Type": "application/json"},
            cookie=cookie,
        )
        self.assertEqual(status, 403)

        status, _, body = self.request(
            "POST",
            "/api/quick-access",
            json.dumps({"path": "docs/notes.txt"}),
            cookie=cookie,
            csrf=True,
            headers={"Content-Type": "application/json"},
        )
        self.assertEqual(status, 201)
        entries = self.json_body(body)["entries"]
        self.assertEqual(len(entries), 1)
        self.assertEqual(entries[0]["path"], "docs/notes.txt")
        self.assertEqual(entries[0]["name"], "notes.txt")
        self.assertIs(entries[0]["isDir"], False)
        self.assertEqual(entries[0]["preview"], "text")

        status, _, body = self.request(
            "POST",
            "/api/quick-access",
            json.dumps({"path": "docs"}),
            cookie=cookie,
            csrf=True,
            headers={"Content-Type": "application/json"},
        )
        self.assertEqual(status, 201)
        entries = self.json_body(body)["entries"]
        self.assertEqual([item["path"] for item in entries], ["docs/notes.txt", "docs"])
        self.assertIs(entries[1]["isDir"], True)
        self.assertIsNone(entries[1]["preview"])

        # Adding the same path twice is idempotent.
        status, _, body = self.request(
            "POST",
            "/api/quick-access",
            json.dumps({"path": "docs"}),
            cookie=cookie,
            csrf=True,
            headers={"Content-Type": "application/json"},
        )
        self.assertEqual(status, 200)
        self.assertEqual(len(self.json_body(body)["entries"]), 2)

        status, _, _ = self.request(
            "POST",
            "/api/quick-access",
            json.dumps({"path": ".."}),
            cookie=cookie,
            csrf=True,
            headers={"Content-Type": "application/json"},
        )
        self.assertEqual(status, 403)

        status, _, _ = self.request(
            "POST",
            "/api/quick-access",
            json.dumps({"path": "missing.txt"}),
            cookie=cookie,
            csrf=True,
            headers={"Content-Type": "application/json"},
        )
        self.assertEqual(status, 404)

        # State file exists with owner-only permissions.
        self.assertTrue(self.state_file.is_file())
        self.assertEqual(self.state_file.stat().st_mode & 0o777, 0o600)

        status, _, body = self.request(
            "POST",
            "/api/quick-access/remove",
            json.dumps({"path": "docs/notes.txt"}),
            cookie=cookie,
            csrf=True,
            headers={"Content-Type": "application/json"},
        )
        self.assertEqual(status, 200)
        payload = self.json_body(body)
        self.assertTrue(payload["removed"])
        self.assertEqual([item["path"] for item in payload["entries"]], ["docs"])

        status, _, body = self.request(
            "POST",
            "/api/quick-access/remove",
            json.dumps({"path": "docs/notes.txt"}),
            cookie=cookie,
            csrf=True,
            headers={"Content-Type": "application/json"},
        )
        self.assertEqual(status, 200)
        self.assertFalse(self.json_body(body)["removed"])

        # A fresh server reading the same state file still sees the entry.
        server2 = lanvault.create_server("127.0.0.1", 0, self.config)
        try:
            self.assertEqual(
                [item["path"] for item in server2.quick_access.entries("alice")],
                ["docs"],
            )
            self.assertEqual(server2.quick_access.entries("bob"), [])
        finally:
            server2.server_close()

        status, _, _ = self.request("GET", "/api/quick-access")
        self.assertEqual(status, 401)

