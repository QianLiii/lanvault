    def test_listing_and_download(self) -> None:
        cookie = self.login()
        status, _, body = self.request("GET", "/api/list", cookie=cookie)
        self.assertEqual(status, 200)
        listing = self.json_body(body)
        names = [entry["name"] for entry in listing["entries"]]
        self.assertEqual(names[:3], ["docs", "文档", "data.bin"])
        self.assertIn("empty.txt", names)
        self.assertEqual(listing["totalSize"], len(self.payload))
        self.assertTrue(listing["writable"])
        self.assertEqual(listing["entries"][0]["kind"], "dir")

        status, headers, body = self.request(
            "GET", "/api/download?path=data.bin", cookie=cookie
        )
        self.assertEqual(status, 200)
        self.assertEqual(body, self.payload)
        self.assertIn("attachment", headers["content-disposition"])
        self.assertIn("bytes", headers["accept-ranges"])
        etag = headers["etag"]

        status, headers, body = self.request(
            "GET",
            "/api/download?path=data.bin",
            cookie=cookie,
            headers={"Range": "bytes=10-19"},
        )
        self.assertEqual(status, 206)
        self.assertEqual(body, self.payload[10:20])
        self.assertEqual(
            headers["content-range"], f"bytes 10-19/{len(self.payload)}"
        )

        status, headers, body = self.request(
            "GET",
            "/api/download?path=data.bin",
            cookie=cookie,
            headers={"Range": "bytes=99999-"},
        )
        self.assertEqual(status, 416)
        self.assertEqual(headers["content-range"], f"bytes */{len(self.payload)}")
        self.assertIn("error", self.json_body(body))

        status, _, body = self.request(
            "HEAD", "/api/download?path=data.bin", cookie=cookie
        )
        self.assertEqual(status, 200)
        self.assertEqual(body, b"")

        status, _, body = self.request(
            "GET",
            "/api/download?path=data.bin",
            cookie=cookie,
            headers={"If-None-Match": etag},
        )
        self.assertEqual(status, 304)
        self.assertEqual(body, b"")

        filename = quote("文档/报告.txt", safe="")
        status, headers, body = self.request(
            "GET", f"/api/download?path={filename}", cookie=cookie
        )
        self.assertEqual(status, 200)
        self.assertEqual(body, b"unicode")
        self.assertIn("filename*=UTF-8''", headers["content-disposition"])

