    @unittest.skipUnless(shutil.which("openssl"), "openssl is required")
    def test_public_key_sign_in_flow(self) -> None:
        private_pem, public_pem = self.generate_keypair()
        cookie = self.login()

        # Register the browser key.
        status, data = self.register_key(cookie, public_pem)
        self.assertEqual(status, 201)
        self.assertTrue(data["created"])
        key_id = data["key"]["id"]
        fingerprint = data["key"]["fingerprint"]
        self.assertEqual(len(fingerprint), 64)

        # Registering the same key again is idempotent.
        status, data = self.register_key(cookie, public_pem)
        self.assertEqual(status, 200)
        self.assertFalse(data["created"])
        self.assertEqual(data["key"]["id"], key_id)

        status, _, body = self.request("GET", "/api/auth/keys", cookie=cookie)
        self.assertEqual(status, 200)
        keys = self.json_body(body)["keys"]
        self.assertEqual(len(keys), 1)
        self.assertEqual(keys[0]["fingerprint"], fingerprint)

        # Keys survive a restart (a fresh store reads the same file).
        reloaded = lanvault.PublicKeyStore(self.config.keys_file)
        self.assertEqual(
            [record["fingerprint"] for record in reloaded.records("alice")],
            [fingerprint],
        )

        # Sign out, then sign in with the key alone.
        status, _, _ = self.request("POST", "/api/logout", b"", cookie=cookie, csrf=True)
        self.assertEqual(status, 204)

        challenge = self.request_challenge()
        self.assertEqual(len(challenge["nonce"]), 64)
        nonce = bytes.fromhex(challenge["nonce"])
        # Browsers send the raw r||s form, not DER.
        signature = base64.b64encode(
            self.der_to_raw_p256(self.sign_message(private_pem, nonce))
        ).decode("ascii")
        status, headers, body = self.request(
            "POST",
            "/api/auth/verify",
            json.dumps({"id": challenge["id"], "signature": signature}),
            csrf=True,
            headers={"Content-Type": "application/json"},
        )
        self.assertEqual(status, 200)
        self.assertEqual(self.json_body(body)["user"], "alice")
        key_cookie = headers.get("set-cookie", "").split(";", 1)[0]
        self.assertTrue(key_cookie.startswith(f"{lanvault.SESSION_COOKIE}="))

        status, _, body = self.request("GET", "/api/session", cookie=key_cookie)
        self.assertEqual(status, 200)
        session = self.json_body(body)
        self.assertEqual(session["user"], "alice")
        self.assertTrue(session["publicKeyAuth"])

        # The challenge is single-use.
        status = self.verify_challenge(challenge["id"], signature)
        self.assertEqual(status, 401)

        # The DER form (as produced by openssl) also verifies.
        challenge = self.request_challenge()
        der_signature = base64.b64encode(
            self.sign_message(private_pem, bytes.fromhex(challenge["nonce"]))
        ).decode("ascii")
        self.assertEqual(self.verify_challenge(challenge["id"], der_signature), 200)

    @unittest.skipUnless(shutil.which("openssl"), "openssl is required")
    def test_public_key_verify_rejects_bad_signature(self) -> None:
        private_pem, public_pem = self.generate_keypair()
        cookie = self.login()
        status, _ = self.register_key(cookie, public_pem)
        self.assertEqual(status, 201)

        # Signature over the wrong message.
        challenge = self.request_challenge()
        signature = base64.b64encode(
            self.sign_message(private_pem, b"not-the-nonce")
        ).decode("ascii")
        self.assertEqual(self.verify_challenge(challenge["id"], signature), 401)

        # Garbage signature in the raw 64-byte form the browser sends.
        challenge = self.request_challenge()
        garbage = base64.b64encode(os.urandom(64)).decode("ascii")
        self.assertEqual(self.verify_challenge(challenge["id"], garbage), 401)

        # An unknown challenge id fails before any crypto runs.
        self.assertEqual(self.verify_challenge("no-such-challenge", garbage), 401)

        # The failed attempts count against the sign-in rate limit:
        # 2 recorded above + 6 here reach the limit of 8.
        for _ in range(6):
            challenge = self.request_challenge()
            self.assertEqual(self.verify_challenge(challenge["id"], garbage), 401)
        challenge = self.request_challenge()
        status, headers, _ = self.request(
            "POST",
            "/api/auth/verify",
            json.dumps({"id": challenge["id"], "signature": garbage}),
            csrf=True,
            headers={"Content-Type": "application/json"},
        )
        self.assertEqual(status, 429)
        self.assertIn("retry-after", headers)

