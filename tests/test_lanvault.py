    def test_path_traversal_and_symlink_escape(self) -> None:
        cookie = self.login()

        status, _, _ = self.request("GET", "/api/list?path=..", cookie=cookie)
        self.assertEqual(status, 403)

        status, _, _ = self.request("GET", "/api/list?path=%2Fetc", cookie=cookie)
        self.assertEqual(status, 400)

        status, _, _ = self.request(
            "GET", "/api/download?path=..%2Foutside%2Fsecret.txt", cookie=cookie
        )
        self.assertEqual(status, 403)

        status, _, _ = self.request(
            "PUT",
            "/api/upload?path=docs&name=..%2Fevil.txt&overwrite=0",
            b"evil",
            cookie=cookie,
            csrf=True,
        )
        self.assertEqual(status, 400)
        self.assertFalse((self.root / "evil.txt").exists())

        try:
            os.symlink(self.outside, self.root / "link-out")
            os.symlink(self.outside / "secret.txt", self.root / "escape.txt")
        except (OSError, NotImplementedError) as exc:
            self.skipTest(f"Symlinks are unavailable: {exc}")

        status, _, body = self.request("GET", "/api/list", cookie=cookie)
        self.assertEqual(status, 200)
        names = [entry["name"] for entry in self.json_body(body)["entries"]]
        self.assertNotIn("link-out", names)
        self.assertNotIn("escape.txt", names)

        status, _, _ = self.request(
            "GET", "/api/download?path=escape.txt", cookie=cookie
        )
        self.assertEqual(status, 403)

        status, _, _ = self.request(
            "GET", "/api/list?path=link-out", cookie=cookie
        )
        self.assertEqual(status, 403)

